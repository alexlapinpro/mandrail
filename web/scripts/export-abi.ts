/** Writes lib/abi.ts from the Foundry build. Run `forge build` in contracts/ first. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const CONTRACTS = ["PolicyGuard", "MandateRegistry", "RiskOracle", "MarketCalendar", "TestUSD", "RWAMarket"];
const out = path.resolve(__dirname, "../../contracts/out");

const blocks = CONTRACTS.map((name) => {
  const { abi } = JSON.parse(readFileSync(path.join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const variable = name === "RWAMarket" ? "rwaMarketAbi" : `${name[0]!.toLowerCase()}${name.slice(1)}Abi`;
  return `export const ${variable} = ${JSON.stringify(abi)} as const;\n`;
});
writeFileSync(
  path.resolve(__dirname, "../lib/abi.ts"),
  `// Generated by scripts/export-abi.ts, do not edit.\n${blocks.join("\n")}`,
);
console.log(`Exported ${CONTRACTS.length} ABIs`);
